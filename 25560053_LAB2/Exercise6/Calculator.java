public class Calculator {
    // Methods
    // Input: a, b (int)
    // Output: a + b
    // Purpose: add 2 ints
    // Approach: a + b
    public int add(int a, int b) {
        return a + b;
    }

    // Input: a, b (double)
    // Output: a + b
    // Purpose: add 2 doubles
    // Approach: a + b
    public double add(double a, double b) {
        return a + b;
    }

    // Input: a, b, c (int)
    // Output: a + b + c
    // Purpose: add 3 ints
    // Approach: a + b + c
    public int add(int a, int b, int c) {
        return a + b + c;
    }

    // Input: a, b (int)
    // Output: larger one
    // Purpose: max of 2 ints
    // Approach: compare a, b
    public int max(int a, int b) {
        return a >= b ? a : b;
    }

    // Input: a, b (double)
    // Output: larger one
    // Purpose: max of 2 doubles
    // Approach: compare a, b
    public double max(double a, double b) {
        return a >= b ? a : b;
    }
}
